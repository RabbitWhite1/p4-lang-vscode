const commaSep = rule => optional(seq(rule, repeat(seq(',', rule)), optional(',')));
const PREC = { conditional: 1, logicalOr: 2, logicalAnd: 3, bitOr: 4, bitXor: 5,
  bitAnd: 6, equality: 7, comparison: 8, shift: 9, additive: 10, multiply: 11,
  unary: 12, postfix: 13 };

module.exports = grammar({
  name: 'p4',
  word: $ => $.identifier,
  extras: $ => [/\s/, $.comment, $.preprocessor],
  conflicts: $ => [
    [$.annotation],
    [$.switch_case],
    [$.call_expression, $.cast_expression, $.binary_expression],
    [$.parenthesized_expression, $.annotation_arguments],
    [$.call_expression, $.binary_expression],
    [$.call_expression, $.unary_expression, $.binary_expression],
    [$.type_parameter, $.named_type],
    [$.named_type, $._expression],
    [$.block_statement, $.list_expression],
  ],
  rules: {
    source_file: $ => repeat(choice($._declaration, ';')),
    _declaration: $ => choice($.aggregate_declaration, $.enum_declaration,
      $.typedef_declaration, $.error_declaration, $.match_kind_declaration,
      $.extern_declaration, $.extern_function_declaration, $.parser_declaration,
      $.control_declaration, $.package_declaration, $.action_declaration,
      $.function_declaration, $.constant_declaration, $.variable_declaration,
      $.instantiation),

    aggregate_declaration: $ => seq(repeat($.annotation),
      field('kind', choice('header', 'header_union', 'struct')),
      field('name', $.identifier), optional($.type_parameters),
      '{', repeat($.field_declaration), '}'),
    field_declaration: $ => seq(repeat($.annotation), field('type', $.type_ref),
      field('name', $.identifier), ';'),
    enum_declaration: $ => seq(repeat($.annotation), 'enum', optional(field('type', $.type_ref)),
      field('name', $.identifier), '{', commaSep($.enum_member), '}'),
    enum_member: $ => seq(repeat($.annotation), field('name', $.identifier),
      optional(seq('=', field('value', $._expression)))),
    typedef_declaration: $ => seq(repeat($.annotation), field('kind', choice('typedef', 'type')),
      field('type', $.type_ref), field('name', $.identifier), ';'),
    error_declaration: $ => seq(repeat($.annotation), 'error', '{', commaSep($.enum_member), '}'),
    match_kind_declaration: $ => seq(repeat($.annotation), 'match_kind', '{', commaSep($.enum_member), '}'),

    extern_declaration: $ => seq(repeat($.annotation), 'extern', field('name', $.identifier),
      optional($.type_parameters), '{', repeat(choice($.method_declaration, $.constructor_declaration)), '}'),
    extern_function_declaration: $ => seq(repeat($.annotation), 'extern', $.function_prototype, ';'),
    function_prototype: $ => seq(field('type', $.type_ref), field('name', $.identifier),
      optional($.type_parameters), field('parameters', $.parameter_list)),
    method_declaration: $ => seq(repeat($.annotation), optional('abstract'), $.function_prototype, ';'),
    constructor_declaration: $ => seq(repeat($.annotation), field('name', $.identifier),
      field('parameters', $.parameter_list), ';'),
    function_declaration: $ => seq(repeat($.annotation), $.function_prototype, field('body', $.block_statement)),
    action_declaration: $ => seq(repeat($.annotation), 'action', field('name', $.identifier),
      field('parameters', $.parameter_list), field('body', $.block_statement)),
    parser_declaration: $ => seq(repeat($.annotation), 'parser', field('name', $.identifier),
      optional($.type_parameters), field('parameters', $.parameter_list),
      optional(field('constructor_parameters', $.parameter_list)),
      choice(';', seq('{', repeat(choice($._local_declaration, $.state_declaration)), '}'))),
    control_declaration: $ => seq(repeat($.annotation), 'control', field('name', $.identifier),
      optional($.type_parameters), field('parameters', $.parameter_list),
      optional(field('constructor_parameters', $.parameter_list)),
      choice(';', seq('{', repeat(choice($._local_declaration, $.apply_block)), '}'))),
    package_declaration: $ => seq(repeat($.annotation), 'package', field('name', $.identifier),
      optional($.type_parameters), field('parameters', $.parameter_list), ';'),
    _local_declaration: $ => choice($.constant_declaration, $.variable_declaration,
      $.instantiation, $.action_declaration, $.table_declaration),
    apply_block: $ => seq('apply', $.block_statement),
    state_declaration: $ => seq(repeat($.annotation), 'state', field('name', $.identifier),
      '{', repeat($._statement), optional($.transition_statement), '}'),
    transition_statement: $ => seq('transition', choice(seq(field('target', $.identifier), ';'), $.select_expression)),
    select_expression: $ => seq('select', $.argument_list, '{', repeat($.select_case), '}'),
    select_case: $ => seq(field('key', $._keyset), ':', field('target', $.identifier), ';'),
    _keyset: $ => choice('default', '_', $._expression),

    parameter_list: $ => seq('(', commaSep($.parameter), ')'),
    parameter: $ => seq(repeat($.annotation), optional(field('direction', choice('in', 'out', 'inout'))),
      field('type', $.type_ref), field('name', $.identifier), optional(seq('=', field('value', $._expression)))),
    type_parameters: $ => seq('<', commaSep($.type_parameter), '>'),
    type_parameter: $ => field('name', $.identifier),
    type_arguments: $ => seq('<', commaSep(choice($.type_ref, '_')), '>'),
    type_ref: $ => seq(choice($.primitive_type, $.named_type, $.tuple_type),
      optional(seq('[', field('size', $._expression), ']'))),
    named_type: $ => seq(optional('.'), field('name', $.identifier), optional($.type_arguments)),
    primitive_type: $ => choice('bool', 'string', 'void', 'error', 'match_kind',
      seq(choice('bit', 'int', 'varbit'), optional(seq('<', choice($.integer, $.identifier,
        $.parenthesized_expression), '>')))),
    tuple_type: $ => seq(choice('tuple', 'list'), $.type_arguments),

    constant_declaration: $ => seq(repeat($.annotation), 'const', field('type', $.type_ref),
      field('name', $.identifier), '=', field('value', $._expression), ';'),
    variable_declaration: $ => seq(repeat($.annotation), field('type', $.type_ref),
      field('name', $.identifier), optional(seq('=', field('value', $._expression))), ';'),
    instantiation: $ => seq(repeat($.annotation), field('type', $.type_ref), $.argument_list,
      field('name', $.identifier), optional(seq('=', '{', repeat($.function_declaration), '}')), ';'),

    table_declaration: $ => seq(repeat($.annotation), 'table', field('name', $.identifier),
      '{', repeat($.table_property), '}'),
    table_property: $ => seq(repeat($.annotation), optional('const'), choice(
      seq(field('name', alias('key', $.identifier)), '=', '{', repeat($.key_element), '}'),
      seq(field('name', alias('actions', $.identifier)), '=', '{', repeat($.action_reference), '}'),
      seq(field('name', alias('entries', $.identifier)), '=', '{', repeat($.table_entry), '}'),
      seq(field('name', $.identifier), '=', field('value', $._expression), ';'))),
    key_element: $ => seq($._expression, ':', field('match_kind', $.identifier), repeat($.annotation), ';'),
    action_reference: $ => seq(repeat($.annotation), choice($.identifier, $.call_expression), ';'),
    table_entry: $ => seq(repeat($.annotation), $._keyset, ':', $._expression,
      repeat($.annotation), optional(seq('priority', '=', $._expression)), ';'),

    _statement: $ => choice($.block_statement, $.variable_declaration, $.constant_declaration,
      $.assignment_statement, $.expression_statement, $.if_statement, $.switch_statement,
      $.return_statement, $.exit_statement, $.for_statement, $.break_statement, $.continue_statement, ';'),
    block_statement: $ => seq(repeat($.annotation), '{', repeat($._statement), '}'),
    assignment_statement: $ => seq(field('left', $._expression), field('operator', choice('=', '+=', '-=', '*=', '/=', '|=', '&=', '^=')),
      field('right', $._expression), ';'),
    expression_statement: $ => seq($._expression, ';'),
    if_statement: $ => prec.right(seq('if', '(', field('condition', $._expression), ')',
      field('consequence', $._statement), optional(seq('else', field('alternative', $._statement))))),
    switch_statement: $ => seq('switch', '(', $._expression, ')', '{', repeat($.switch_case), '}'),
    switch_case: $ => seq(choice('default', $._expression), ':', optional($.block_statement)),
    return_statement: $ => seq('return', optional($._expression), ';'),
    exit_statement: () => seq('exit', ';'),
    break_statement: () => seq('break', ';'),
    continue_statement: () => seq('continue', ';'),
    for_statement: $ => seq('for', '(', choice(
      seq(optional($.for_initializer), ';', optional($._expression), ';', commaSep($.for_update)),
      seq(field('type', $.type_ref), field('name', $.identifier), 'in', $._expression)), ')', $._statement),
    for_initializer: $ => choice(seq($.type_ref, $.identifier, '=', $._expression), $.for_update),
    for_update: $ => choice(seq($._expression, '=', $._expression), $._expression),

    _expression: $ => choice($.identifier, $.integer, $.string, $.boolean,
      $.parenthesized_expression, $.member_expression, $.call_expression, $.index_expression,
      $.slice_expression, $.cast_expression, $.unary_expression, $.binary_expression,
      $.conditional_expression, $.list_expression, $.struct_expression),
    parenthesized_expression: $ => seq('(', $._expression, repeat(seq(',', $._expression)), ')'),
    member_expression: $ => prec.left(PREC.postfix, seq(field('object', $._expression), '.', field('property', $.member_name))),
    member_name: $ => choice($.identifier, $.integer, alias('apply', $.identifier), alias('state', $.identifier), alias('type', $.identifier)),
    call_expression: $ => prec(PREC.postfix, seq(field('function', $._expression),
      optional($.type_arguments), field('arguments', $.argument_list))),
    argument_list: $ => seq('(', commaSep($.argument), ')'),
    argument: $ => choice($._expression, seq(field('name', $.identifier), '=', field('value', $._expression)), '_', 'default'),
    index_expression: $ => prec.left(PREC.postfix, seq(field('object', $._expression), '[', field('index', $._expression), ']')),
    slice_expression: $ => prec.left(PREC.postfix, seq(field('object', $._expression), '[', $._expression, choice(':', '+:'), $._expression, ']')),
    cast_expression: $ => prec(PREC.unary, seq('(', field('type', $.type_ref), ')', field('value', $._expression))),
    unary_expression: $ => prec(PREC.unary, seq(field('operator', choice('!', '~', '-', '+')), field('argument', $._expression))),
    binary_expression: $ => choice(...[
      [PREC.logicalOr, '||'], [PREC.logicalAnd, '&&'], [PREC.bitOr, '|'],
      [PREC.bitXor, '^'], [PREC.bitAnd, '&'], [PREC.equality, choice('==', '!=')],
      [PREC.comparison, choice('<', '<=', '>', '>=')], [PREC.shift, choice('<<', '>>')],
      [PREC.additive, choice('+', '-', '|+|', '|-|', '++')], [PREC.multiply, choice('*', '/', '%')],
      [PREC.conditional, choice('&&&', '..')]
    ].map(([precedence, operator]) => prec.left(precedence,
      seq(field('left', $._expression), field('operator', operator), field('right', $._expression))))),
    conditional_expression: $ => prec.right(PREC.conditional, seq($._expression, '?', $._expression, ':', $._expression)),
    list_expression: $ => seq('{', commaSep($._expression), '}'),
    struct_expression: $ => seq(field('type', $.named_type), '{', commaSep($.struct_initializer), '}'),
    struct_initializer: $ => seq(field('name', $.identifier), '=', $._expression),

    annotation: $ => seq('@', field('name', $.identifier), optional(choice($.annotation_arguments, $.structured_annotation))),
    annotation_arguments: $ => seq('(', commaSep(choice($._expression, $.annotation, $.annotation_arguments)), ')'),
    structured_annotation: $ => seq('[', commaSep(choice($._expression, $.struct_initializer)), ']'),
    identifier: () => /[a-zA-Z_][a-zA-Z0-9_]*/,
    integer: () => /([0-9][0-9_]*[ws])?(0[xX][0-9a-fA-F_]+|0[bB][01_]+|0[oO][0-7_]+|0[dD][0-9_]+|[0-9][0-9_]*)/,
    string: () => token(seq('"', repeat(choice(/[^"\\\r\n]/, /\\./)), '"')),
    boolean: () => choice('true', 'false'),
    comment: () => token(choice(seq('//', /[^\r\n]*/), seq('/*', /[^*]*\*+([^/*][^*]*\*+)*/, '/'))),
    preprocessor: () => token(seq('#', repeat(choice(/[^\r\n\\]/, /\\\r?\n/, /\\[^\r\n]/))))
  }
});
